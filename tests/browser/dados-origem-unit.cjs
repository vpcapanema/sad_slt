const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const context = {window:{}};
vm.runInNewContext(fs.readFileSync('assets/js/dados-origem.js','utf8'), context);
const ui = context.window.SLTDadosOrigem;
const a = {arquivo:'fonte.csv', campos:{Codigo:'001', Numero:0, Ativo:false, Nome:'<script>alert(1)</script>', Local:{Cidade:'A'}, Lista:['a','b']}};
const b = {campos:{Outro:'B', Codigo:'002', 'Local / Cidade':'C'}};
const fields = ui.columns([{dados_origem:a},{dados_origem:b},{dados_origem:null}]);
assert.equal(fields.filter(f=>f.label==='Codigo').length,1);
assert.equal(fields.filter(f=>f.label==='Local / Cidade').length,2);
assert.equal(ui.text(ui.value(a,fields.find(f=>f.label==='Codigo'))),'001');
assert.equal(ui.text(0),'0');
assert.equal(ui.text(false),'Não');
assert.equal(ui.text(null),'—');
assert.equal(ui.details(null),'');
assert(!ui.details(a).includes('<script>'));
assert(ui.details(a).includes('&lt;script&gt;'));
assert(ui.details(a).includes('Arquivo de origem'));
console.log('PASS original values, heterogeneous and nested fields, missing values and HTML escaping');
