const assert=require('node:assert/strict');
(async()=>{
 const {validarEntradas}=await import('../../geoespacial/extracao-atributos/lote.js');
 const {entradasParaPrevia,entradaConfirmada}=await import('../../geoespacial/extracao-atributos/preparacao.js');
 const layer=id=>({id,nome:id,tipo:'vetor',status_validacao:'valida',representacao:'tiles',tiles_url:'/tiles',revisao:'nova',feicoes:1,metadados_local:{identificacao:{total:1,campos:[],completa:true}}});
 const entry={layer:layer('a'),config:{identificacao_confirmada:true}};
 const state={input:'a',inputConfig:entry.config,catalog:[entry.layer],entradasExtras:[]};
 assert.equal(entradasParaPrevia(state).length,0,'Confirmação antiga não dispensa validação');
 let release;const pending=new Promise(resolve=>release=resolve);
 const validating=validarEntradas([entry],{validarCamada:async()=>{await pending;return layer('a');}});
 assert.equal(entradasParaPrevia(state).length,0,'Não admite camada durante validação');
 release();await validating;
 assert.equal(entradasParaPrevia(state).length,1);
 assert.equal(entradaConfirmada(entry.layer,entry.config),true,'Mesmo critério fecha o card e libera a prévia');
 entry.layer.revisao='alterada';assert.equal(entradasParaPrevia(state).length,0,'Alteração da camada exige nova validação');
 const batch=['a','b'].map(id=>({layer:layer(id),config:{}}));
 await assert.rejects(validarEntradas(batch,{validarCamada:async ref=>{if(ref.id==='b')throw Error('falha');return layer(ref.id);}}),/falha/);
 assert(batch.every(e=>!e.config.identificacao_confirmada),'Falha não admite lote parcial');
 const original={nome:'arquivo.gpkg',conteudo_base64:'AAE='};
 const source={arquivo_local:original};let calls=0;
 const locals=['x','y'].map(chave=>({layer:{...layer(chave),chave},origem:source,config:{}}));
 await validarEntradas(locals,{validarEntradaLocal:async arquivo=>{assert.equal(arquivo,original);calls++;return ['x','y'].map(chave=>({...layer('novo'),chave}));}});
 assert.equal(calls,1,'Arquivo bruto validado uma vez para todos os componentes');
 assert.deepEqual(locals.map(e=>e.layer.id),['x','y']);assert(locals.every(e=>entradaConfirmada(e.layer,e.config)));
 const invalid={layer:layer('id'),config:{campo_id:'inexistente'}};
 await assert.rejects(validarEntradas([invalid],{validarCamada:async()=>layer('id')}),/não existe/);
 assert(!invalid.config.identificacao_confirmada);
 console.log('Entrada: validação obrigatória, espera, falha atômica, revisão e arquivo bruto: OK');
})().catch(e=>{console.error(e);process.exitCode=1;});
