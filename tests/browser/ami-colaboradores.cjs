const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  try {
    const page = await browser.newPage(), errors=[], writes=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.route('**/api/**',r=>{
      const path=new URL(r.request().url()).pathname;
      if(r.request().method()!=='GET') writes.push(path);
      if(path==='/api/ahp/comparacao-colaborativa/ambientes') return r.fulfill({json:[{id:'j1',nome:'Julgamento',status:'ativa',criterios:[],convites:[{email:'existente@example.com',nome:'Existente'}]}]});
      return r.fulfill({json:path==='/api/auth/me'?{id:'u',nome:'Analista',tipo_usuario:'ANALISTA'}:path==='/api/auth/session'?{authenticated:true,user:{id:'u',tipo_usuario:'ANALISTA'}}:[]});
    });
    await page.goto('http://127.0.0.1:8083/restrict/analise-multicriterio/?modo=espaco');
    const editGroup=page.locator('#ami-environment-edit');
    assert.equal(await editGroup.isDisabled(),true);
    assert.equal(await page.locator('#ami-create-section #ami-environment-edit').count(),0);
    assert.equal(await page.locator('.ami-table-actions #ami-environment-edit .fa-pen-to-square').count(),1);
    await page.locator('#ami-judgments [data-select-id]').first().check();
    await editGroup.click();
    assert.equal(await page.locator('#ami-create-section > .ahp-section-label #ami-environment-save').count(),0);
    assert.equal(await page.locator('#ami-environment-actions button:visible').count(),2);
    assert.equal(await page.locator('#ami-environment-save').isVisible(),true);
    assert.match(await page.locator('#ami-create-cancel').textContent(),/Cancelar edição/);
    assert.equal(await page.getByLabel('E-mail do colaborador 1',{exact:true}).inputValue(),'existente@example.com');
    assert.equal(await page.locator('#ami-cancel-emails').isEnabled(),true);
    await page.locator('#ami-cancel-emails').click();
    assert.match(await page.locator('#ami-email-list').textContent(),/existente@example.com/);
    assert.equal(await page.locator('#ami-criteria-matrix-summary').evaluate(el=>el.tagName),'P');
    assert.equal(await page.locator('#ami-criteria-matrix-summary').evaluate(el=>el.classList.contains('ahp-info-note')),false);
    await page.locator('#ami-new').click();
    const submit=page.locator('#ami-create-form button[type="submit"]');
    assert.equal(await submit.isDisabled(),true);
    await page.locator('#ami-emails').fill('ana@example.com; bia@example.com');
    await page.locator('#ami-add-emails').click();
    assert.equal(await page.locator('#ami-email-list tr').count(),2);
    await page.getByLabel('Nome do colaborador 1',{exact:true}).fill('Ana');
    await page.locator('#ami-confirm-emails').click();
    assert.equal(await submit.isEnabled(),true);
    assert.equal(await page.locator('#ami-add-emails').isDisabled(),true);
    assert.equal(await page.locator('#ami-email-list input[type="text"]').count(),0);
    await page.locator('#ami-edit-emails').click();
    await page.getByLabel('Nome do colaborador 1',{exact:true}).fill('Alterada');
    await page.locator('#ami-email-list [data-draft-index="1"]').check();
    await page.locator('#ami-delete-emails').click();
    assert.equal(await page.locator('#ami-email-list tr').count(),1);
    await page.locator('#ami-cancel-emails').click();
    assert.equal(await page.locator('#ami-email-list tr').count(),2);
    assert.match(await page.locator('#ami-email-list').textContent(),/Ana/);
    assert.doesNotMatch(await page.locator('#ami-email-list').textContent(),/Alterada/);
    await page.locator('#ami-edit-emails').click();
    await page.getByLabel('E-mail do colaborador 2',{exact:true}).fill('ana@example.com');
    await page.locator('#ami-confirm-emails').click();
    assert.match(await page.locator('#ami-emails-feedback').textContent(),/repetidos/);
    assert.equal(await submit.isDisabled(),true);
    await page.getByLabel('E-mail do colaborador 2',{exact:true}).fill('invalido');
    await page.locator('#ami-confirm-emails').click();
    assert.match(await page.locator('#ami-emails-feedback').textContent(),/válido/);
    await page.locator('#ami-select-all').check();
    await page.locator('#ami-delete-emails').click();
    assert.equal(await page.locator('#ami-confirm-emails').isDisabled(),true);
    await page.locator('#ami-cancel-emails').click();
    assert.equal(await page.locator('#ami-email-list tr').count(),2);
    assert.equal(await page.locator('[aria-label="Controles do julgamento"] #ami-delete-emails').count(),0);
    await page.locator('#ami-new').click();
    await page.locator('#ami-emails').fill(Array.from({length:17},(_,i)=>`p${i+1}@example.com`).join(';'));
    await page.locator('#ami-add-emails').click();
    assert.equal(await page.locator('#ami-email-list tr').count(),15);
    await page.locator('#ami-select-all').check();
    assert.match(await page.locator('#ami-emails-count').textContent(),/^15 selecionados \/ 15 na página \/ 17 no total$/);
    await page.locator('#ami-emails-pagination button').last().click();
    assert.equal(await page.locator('#ami-email-list tr').count(),2);
    assert.match(await page.locator('#ami-emails-count').textContent(),/^0 selecionados \/ 2 na página \/ 17 no total$/);
    await page.getByLabel('Nome do colaborador 17',{exact:true}).fill('Ultimo');
    await page.locator('#ami-emails-filter-coluna').selectOption('email');
    await page.locator('#ami-emails-filter-valor').selectOption('p17@example.com');
    assert.equal(await page.locator('#ami-email-list tr').count(),1);
    assert.equal(await page.getByLabel('Nome do colaborador 17',{exact:true}).inputValue(),'Ultimo');
    await page.locator('#ami-emails-filter-inverter').click();
    assert.equal(await page.locator('#ami-email-list tr').count(),15);
    await page.locator('#ami-emails-pagination button').last().click();
    assert.equal(await page.locator('#ami-email-list tr').count(),1);
    await page.locator('#ami-emails-filter-limpar').click();
    await page.locator('#ami-emails-filter-coluna').selectOption('email');
    await page.locator('#ami-emails-filter-valor').selectOption('p17@example.com');
    await page.locator('#ami-select-all').check();
    await page.locator('#ami-delete-emails').click();
    await page.locator('#ami-emails-filter-limpar').click();
    assert.match(await page.locator('#ami-emails-count').textContent(),/16 no total$/);
    await page.locator('#ami-emails-pagination button').last().click();
    assert.equal(await page.locator('#ami-email-list tr').count(),1);
    assert.equal(await page.getByLabel('E-mail do colaborador 16',{exact:true}).inputValue(),'p16@example.com');
    assert.deepEqual(writes,[]);
    assert.deepEqual(errors,[]);
    console.log('Colaboradores: editar, excluir, cancelar, confirmar, validar e separar controles OK; sem gravacoes.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
